def _owned_project(request, pk) -> Project:
    p = Project.objects.filter(pk=pk).first()
    if p is None:
        raise ValidationError('프로젝트 없음')
    if p.user_id != request.user.id and request.user.role != 'admin':
        raise ValidationError('권한 없음')
    return p


@api_view(['GET'])
@permission_classes([IsAuthenticated])
def qna(request, pk):
    from apps.pipeline.models import GeneratedQnA
    rows = GeneratedQnA.objects.filter(project=_owned_project(request, pk))
    return Response([
        {'menuLabel': r.menu_label, 'question': r.question, 'answerMd': r.answer_md}
        for r in rows
    ])


@api_view(['GET'])
@permission_classes([IsAuthenticated])
def widget_config(request, pk):
    w = Widget.current(_owned_project(request, pk))
    if w is None:
        raise ValidationError('아직 생성된 위젯이 없습니다.')
    return Response({'config': w.public_config()})   # system_prompt 미포함


@api_view(['GET'])
@permission_classes([IsAuthenticated])
def download_config_js(request, pk):
    w = Widget.current(_owned_project(request, pk))
    if w is None:
        raise ValidationError('위젯 없음')
    js = f'// Auto-generated by WebMCP Auto\nwindow.WebMCPConfig = {w.config_json};\n'
    resp = HttpResponse(js, content_type='application/javascript')
    resp['Content-Disposition'] = 'attachment; filename="webmcp-config.js"'
    from apps.projects.models import DownloadLog
    DownloadLog.objects.create(project_id=pk, user=request.user, file_type='config_js')
    return resp


@api_view(['GET'])
@permission_classes([IsAuthenticated])
def download_bundle(request, pk):
    """자체 호스팅 번들 zip."""
    import io
    import zipfile
    from pathlib import Path

    project = _owned_project(request, pk)
    w = Widget.current(project)
    if w is None:
        raise ValidationError('위젯 없음')

    dist_dir = Path(settings.BASE_DIR).parent / 'widget-dist'
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w') as zf:
        zf.writestr('webmcp-config.js', f'window.WebMCPConfig = {w.config_json};\n')
        # JS 파일은 난독화+최적화, CSS 는 그대로 (스타일시트는 난독화 불가)
        for name in ['webmcp.js', 'widget.js', 'webmcp-widget.js']:
            f = dist_dir / name
            if f.exists():
                zf.writestr(name, minify_js(f.read_text()))
        css = dist_dir / 'widget.css'
        if css.exists():
            zf.writestr('widget.css', css.read_text())
        zf.writestr('INSTALL.md', _install_md(project))
    resp = HttpResponse(buf.getvalue(), content_type='application/zip')
    resp['Content-Disposition'] = f'attachment; filename="webmcp-bundle-{project.public_id}.zip"'
    from apps.projects.models import DownloadLog
    DownloadLog.objects.create(project=project, user=request.user, file_type='bundle_zip')
    return resp


